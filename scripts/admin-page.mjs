// Embeds the admin page (mcp-server/src/admin-page.html) in a generated module so every bundle and test carries the
// same bytes without reading a file next to the bundle at run time. --write regenerates it; --check fails on drift.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(ROOT, "mcp-server", "src", "admin-page.generated.ts");

export function renderAdminPageModule(root = ROOT) {
  const html = readFileSync(path.join(root, "mcp-server", "src", "admin-page.html"), "utf8").replace(/\r\n/g, "\n");
  return `// Generated by scripts/admin-page.mjs from admin-page.html. Do not edit.\nexport const ADMIN_PAGE_HTML: string = ${JSON.stringify(html)};\n`;
}

export function writeAdminPageModule() {
  writeFileSync(OUTPUT, renderAdminPageModule());
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") !== renderAdminPageModule()) {
      console.error("mcp-server/src/admin-page.generated.ts is out of date: run node scripts/admin-page.mjs --write");
      process.exit(1);
    }
  } else {
    writeAdminPageModule();
  }
}
